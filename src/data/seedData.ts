export function calculateFare(
  vehicleType: VehicleServiceType,
  distanceKm: number,
  isRoundTrip: boolean,
  passengerCount: number
): { grossFare: number; driverPayout: number; companyProfit: number } {
  const config = VEHICLE_SERVICE_CONFIG[vehicleType];
  let distanceCharge = distanceKm * config.perKmRate;
  let total = config.baseFare + distanceCharge;

  if (isRoundTrip) {
    total = total * 1.85; // 15% round-trip discount
  }

  if (passengerCount > 4) {
    total += (passengerCount - 4) * 5; // $5 surcharge per extra passenger over 4
  }

  const grossFare = Math.round(total * 100) / 100;
  const driverPayout = Math.round(grossFare * 0.75 * 100) / 100; // 75% payout
  const companyProfit = Math.round((grossFare - driverPayout) * 100) / 100;

  return { grossFare, driverPayout, companyProfit };
}

